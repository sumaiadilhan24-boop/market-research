-- Market Research v3.0 — one-click Supabase setup
-- Run this entire file once in the Supabase SQL Editor (SQL Editor → New query → Run).

CREATE EXTENSION IF NOT EXISTS "uuid-ossp";

-- 1. Products
CREATE TABLE IF NOT EXISTS products (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    breed_or_type TEXT,
    target_price NUMERIC(10, 2) NOT NULL,
    min_acceptable_price NUMERIC(10, 2),
    icon_type TEXT DEFAULT 'emoji',        -- 'emoji' | 'lucide' | 'url'
    icon_value TEXT DEFAULT '📦',
    status TEXT DEFAULT 'AVAILABLE',       -- 'AVAILABLE' | 'RESERVED' | 'SOLD'
    sold_price NUMERIC(10, 2),
    sold_at TIMESTAMPTZ,
    sold_note TEXT,
    notes TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- 2. Visits (date-based market research sessions)
CREATE TABLE IF NOT EXISTS visits (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    visit_date DATE NOT NULL DEFAULT CURRENT_DATE,
    title TEXT NOT NULL,
    location TEXT,
    notes TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 3. Customer interactions
CREATE TABLE IF NOT EXISTS interactions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    direction TEXT DEFAULT 'SELL',          -- 'SELL' = buyer offered | 'BUY' = seller quoted
    visit_id BIGINT NOT NULL REFERENCES visits(id) ON DELETE CASCADE,
    product_id BIGINT NOT NULL REFERENCES products(id) ON DELETE CASCADE,
    questions JSONB DEFAULT '[]'::jsonb,
    custom_question TEXT,
    offered_price NUMERIC(10, 2),
    customer_sentiment TEXT,               -- 'HIGH_INTEREST' | 'CASUAL' | 'BARGAIN' | 'READY_TO_BUY'
    customer_notes TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- Upgrade-safe additions for projects created with an earlier schema.
ALTER TABLE products ADD COLUMN IF NOT EXISTS sold_note TEXT;
ALTER TABLE interactions ADD COLUMN IF NOT EXISTS direction TEXT DEFAULT 'SELL';

CREATE INDEX IF NOT EXISTS interactions_visit_id_idx ON interactions (visit_id);
CREATE INDEX IF NOT EXISTS interactions_product_id_idx ON interactions (product_id);
CREATE INDEX IF NOT EXISTS interactions_created_at_idx ON interactions (created_at);

-- Email/password authentication: only signed-in users may read or write data.
ALTER TABLE products ENABLE ROW LEVEL SECURITY;
ALTER TABLE visits ENABLE ROW LEVEL SECURITY;
ALTER TABLE interactions ENABLE ROW LEVEL SECURITY;

-- Remove legacy open-anon policies if this project was set up with an older version.
DROP POLICY IF EXISTS "Allow public read on products" ON products;
DROP POLICY IF EXISTS "Allow public insert on products" ON products;
DROP POLICY IF EXISTS "Allow public update on products" ON products;
DROP POLICY IF EXISTS "Allow public delete on products" ON products;
DROP POLICY IF EXISTS "Allow public read on visits" ON visits;
DROP POLICY IF EXISTS "Allow public insert on visits" ON visits;
DROP POLICY IF EXISTS "Allow public update on visits" ON visits;
DROP POLICY IF EXISTS "Allow public delete on visits" ON visits;
DROP POLICY IF EXISTS "Allow public read on interactions" ON interactions;
DROP POLICY IF EXISTS "Allow public insert on interactions" ON interactions;
DROP POLICY IF EXISTS "Allow public update on interactions" ON interactions;
DROP POLICY IF EXISTS "Allow public delete on interactions" ON interactions;

DO $$
DECLARE
    t TEXT;
    op TEXT;
    pol TEXT;
BEGIN
    FOREACH t IN ARRAY ARRAY['products', 'visits', 'interactions'] LOOP
        FOREACH op IN ARRAY ARRAY['SELECT', 'INSERT', 'UPDATE', 'DELETE'] LOOP
            pol := 'Authenticated ' || lower(op) || ' on ' || t;
            IF NOT EXISTS (SELECT 1 FROM pg_policies WHERE tablename = t AND policyname = pol) THEN
                IF op = 'SELECT' THEN
                    EXECUTE format('CREATE POLICY %I ON %I FOR SELECT TO authenticated USING (true)', pol, t);
                ELSIF op = 'INSERT' THEN
                    EXECUTE format('CREATE POLICY %I ON %I FOR INSERT TO authenticated WITH CHECK (true)', pol, t);
                ELSIF op = 'UPDATE' THEN
                    EXECUTE format('CREATE POLICY %I ON %I FOR UPDATE TO authenticated USING (true)', pol, t);
                ELSE
                    EXECUTE format('CREATE POLICY %I ON %I FOR DELETE TO authenticated USING (true)', pol, t);
                END IF;
            END IF;
        END LOOP;
    END LOOP;
END $$;
